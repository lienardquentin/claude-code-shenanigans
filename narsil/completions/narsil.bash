_narsil() {
    local i cur prev opts cmd
    COMPREPLY=()
    if [[ "${BASH_VERSINFO[0]}" -ge 4 ]]; then
        cur="$2"
    else
        cur="${COMP_WORDS[COMP_CWORD]}"
    fi
    prev="$3"
    cmd=""
    opts=""

    for i in "${COMP_WORDS[@]:0:COMP_CWORD}"
    do
        case "${cmd},${i}" in
            ",$1")
                cmd="narsil"
                ;;
            narsil,archive)
                cmd="narsil__subcmd__archive"
                ;;
            narsil,completions)
                cmd="narsil__subcmd__completions"
                ;;
            narsil,copy)
                cmd="narsil__subcmd__copy"
                ;;
            narsil,forge)
                cmd="narsil__subcmd__forge"
                ;;
            narsil,help)
                cmd="narsil__subcmd__help"
                ;;
            narsil,ls)
                cmd="narsil__subcmd__ls"
                ;;
            narsil,scribe)
                cmd="narsil__subcmd__scribe"
                ;;
            narsil,seal)
                cmd="narsil__subcmd__seal"
                ;;
            narsil,show)
                cmd="narsil__subcmd__show"
                ;;
            narsil,sync)
                cmd="narsil__subcmd__sync"
                ;;
            narsil,tally)
                cmd="narsil__subcmd__tally"
                ;;
            narsil__subcmd__archive,help)
                cmd="narsil__subcmd__archive__subcmd__help"
                ;;
            narsil__subcmd__archive,prune)
                cmd="narsil__subcmd__archive__subcmd__prune"
                ;;
            narsil__subcmd__archive__subcmd__help,help)
                cmd="narsil__subcmd__archive__subcmd__help__subcmd__help"
                ;;
            narsil__subcmd__archive__subcmd__help,prune)
                cmd="narsil__subcmd__archive__subcmd__help__subcmd__prune"
                ;;
            narsil__subcmd__help,archive)
                cmd="narsil__subcmd__help__subcmd__archive"
                ;;
            narsil__subcmd__help,completions)
                cmd="narsil__subcmd__help__subcmd__completions"
                ;;
            narsil__subcmd__help,copy)
                cmd="narsil__subcmd__help__subcmd__copy"
                ;;
            narsil__subcmd__help,forge)
                cmd="narsil__subcmd__help__subcmd__forge"
                ;;
            narsil__subcmd__help,help)
                cmd="narsil__subcmd__help__subcmd__help"
                ;;
            narsil__subcmd__help,ls)
                cmd="narsil__subcmd__help__subcmd__ls"
                ;;
