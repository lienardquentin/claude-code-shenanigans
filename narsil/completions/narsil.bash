                cmd="narsil__subcmd__help__subcmd__sync"
                ;;
            narsil__subcmd__help,tally)
                cmd="narsil__subcmd__help__subcmd__tally"
                ;;
            narsil__subcmd__help__subcmd__archive,prune)
                cmd="narsil__subcmd__help__subcmd__archive__subcmd__prune"
                ;;
            *)
                ;;
        esac
    done

