                --before)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                --chronicle)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                *)
                    COMPREPLY=()
                    ;;
            esac
            COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
            return 0
            ;;
