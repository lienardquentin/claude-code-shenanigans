<#
.SYNOPSIS
  Builds hooks/terminals.ts from the research file, so that the terminal guide holds only what that file says.

.DESCRIPTION
  Reads docs/research/terminal-capabilities.md (the tables under "Windows", "macOS", "Linux" and "Multiplexers and
  hosts"), takes from each capability cell its value (`yes`, `no`, `partial` or `unknown`: the first one in the cell)
  and the cell's words with the source markers taken out, and writes them as a TypeScript module. Nothing is added.

.EXAMPLE
  powershell -NoProfile -File .claude\mods\mermaid-view\tools\build-terminals.ps1
#>
param(
  [string]$Research = (Join-Path $PSScriptRoot '..\..\..\..\docs\research\terminal-capabilities.md'),
  [string]$Out = (Join-Path $PSScriptRoot '..\hooks\terminals.ts')
)

$ErrorActionPreference = 'Stop'
$utf8 = New-Object System.Text.UTF8Encoding $false
$lines = [System.IO.File]::ReadAllLines((Resolve-Path $Research).Path, $utf8)

$sections = @{ 'Windows' = 'windows'; 'macOS' = 'macos'; 'Linux' = 'linux'; 'Multiplexers and hosts' = 'host' }
$os = $null
$rows = New-Object System.Collections.ArrayList
$read = ($lines | Where-Object { $_ -match '^\- \*\*Date read\*\*' } | Select-Object -First 1)
$date = if ($read -match '(\d{4}-\d{2}-\d{2})') { $Matches[1] } else { 'unknown' }

function Clean([string]$text) {
  # The source markers go; so do the spaces they leave before punctuation and inside brackets
  $t = $text -replace '\[S\d+[a-z]?\]', '' -replace '\s+', ' '
  $t = $t -replace '\\\|', '|'
  $t = $t -replace '\s+([.;,)])', '$1' -replace '\(\s+', '('
  return $t.Trim().TrimEnd('.', ';', ',').Trim()
}

function Quote([string]$text) {
  $escaped = $text.Replace('\', '\\').Replace("'", "\'")
  return "'" + $escaped + "'"
}

foreach ($line in $lines) {
  if ($line -match '^## (.+)$') {
    $name = $Matches[1].Trim()
    $os = if ($sections.ContainsKey($name)) { $sections[$name] } else { $null }
    continue
  }
  if ($null -eq $os) { continue }
  if ($line -notmatch '^\|') { continue }
  if ($line -match '^\|\s*-') { continue }

  $cells = @([regex]::Split($line.Trim().Trim('|'), '(?<!\\)\|') | ForEach-Object { $_.Trim() })
  if ($cells.Count -lt 5) { continue }
  # The header row of a table names its first column Terminal or Host
  if ($cells[0] -in @('Terminal', 'Host')) { continue }

  $capabilities = @()
  foreach ($index in 1..4) {
    $cell = $cells[$index]
    $value = if ($cell -match '`(yes|no|partial|unknown)`') { $Matches[1] } else { 'unknown' }
    $capabilities += [pscustomobject]@{ value = $value; note = (Clean (([regex]'`(yes|no|partial|unknown)`\s*').Replace($cell, '', 1))) }
  }

  [void]$rows.Add([pscustomobject]@{
      os = $os
      name = (Clean $cells[0])
      images = $capabilities[0]
      mouse = $capabilities[1]
      links = $capabilities[2]
      recognise = $capabilities[3]
      notes = if ($cells.Count -gt 5) { Clean $cells[5] } else { '' }
    })
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// Generated by tools/build-terminals.ps1 from docs/research/terminal-capabilities.md: do not edit by hand.')
[void]$sb.AppendLine('// Every value and every word below is that file''s; nothing is added here.')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('export type Value = ''yes'' | ''no'' | ''partial'' | ''unknown''')
[void]$sb.AppendLine('export type Capability = { value: Value; note: string }')
[void]$sb.AppendLine('export type Terminal = {')
[void]$sb.AppendLine('  os: ''windows'' | ''macos'' | ''linux'' | ''host''')
[void]$sb.AppendLine('  name: string')
[void]$sb.AppendLine('  images: Capability')
[void]$sb.AppendLine('  mouse: Capability')
[void]$sb.AppendLine('  links: Capability')
[void]$sb.AppendLine('  recognise: Capability')
[void]$sb.AppendLine('  notes: string')
[void]$sb.AppendLine('}')
[void]$sb.AppendLine('')
[void]$sb.AppendLine("/** The day the sources of the research file were read. */")
[void]$sb.AppendLine("export const READ_ON = '$date'")
[void]$sb.AppendLine('')
[void]$sb.AppendLine('export const TERMINALS: readonly Terminal[] = [')
foreach ($r in $rows) {
  [void]$sb.AppendLine('  {')
  [void]$sb.AppendLine("    os: '$($r.os)',")
  [void]$sb.AppendLine("    name: $(Quote $r.name),")
  foreach ($k in 'images', 'mouse', 'links', 'recognise') {
    $c = $r.$k
    [void]$sb.AppendLine("    ${k}: { value: '$($c.value)', note: $(Quote $c.note) },")
  }
  [void]$sb.AppendLine("    notes: $(Quote $r.notes),")
  [void]$sb.AppendLine('  },')
}
[void]$sb.AppendLine(']')

[System.IO.File]::WriteAllText($Out, $sb.ToString(), $utf8)
Write-Output "wrote $($rows.Count) rows to $Out"
